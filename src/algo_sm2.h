#ifndef ALGO_SM2_H
#define ALGO_SM2_H

/*
模块职责：
- 提供一次复习反馈到“掌握度/间隔/连续答对次数”的纯函数计算。

关键约束：
- 算法层不读写全局容器、不保存文件、不读取日期；调用方负责把结果写回业务对象。
- score 是交互层约定的 1/2/3 三档，不能与旧版 0/1/2 复习结果混用。
*/

// ================================================================
// 纯数据结构：复习结果
// ================================================================
struct ReviewResult {
    int newMastery;
    int newInterval;
    int correctStreak;
};

// ================================================================
// 纯函数算法：简化 SM-2 记忆模型
// ================================================================
// 评分标准 (score):
// 1 = 忘记 (重置间隔，扣除较大掌握度)
// 2 = 模糊 (间隔不变，微调掌握度)
// 3 = 记牢 (间隔拉长，增加较大掌握度)
// ================================================================
// 参数：oldMastery 建议在 0~100，oldInterval 最小业务值为 1，score 必须是 1/2/3。
// 返回：newMastery 会钳制在 0~100，newInterval 至少为 1。
ReviewResult calculateNextReview(int oldMastery, int oldInterval, int oldStreak, int score);

#endif
