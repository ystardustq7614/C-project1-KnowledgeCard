#ifndef ALGO_SM2_H
#define ALGO_SM2_H

/*
[导读]
- 本头文件声明简化 SM-2 复习间隔算法，是 review.cpp 更新复习状态前的纯计算层。

[输入输出]
- 输入：旧掌握度、旧间隔、旧连续答对次数、评分 score。
- 输出：新的掌握度、间隔和连续答对次数。

[易错点]
- 算法层不读写全局容器、不保存文件、不读取日期；调用方负责把结果写回业务对象。
- score 是交互层约定的 1/2/3 三档，不能与旧版 0/1/2 复习结果混用。
*/

// ================================================================
// 纯数据结构：复习结果
// ================================================================
struct ReviewResult {
    // 复习后的掌握度，调用方会写回 Card/WrongQuestion.mastery。
    int newMastery;
    // 复习后的间隔天数，调用方会写回 intervalDays。
    int newInterval;
    // 复习后的连续答对次数，评分低时会被重置。
    int correctStreak;
};

// ================================================================
// 纯函数算法：简化 SM-2 记忆模型
// ================================================================
// 评分标准 (score):
// 1 = 忘记 (重置间隔，扣除较大掌握度)
// 2 = 模糊 (间隔不变，微调掌握度)
// 3 = 记牢 (间隔拉长，增加较大掌握度)
// ================================================================
// 参数：oldMastery 建议在 0~100，oldInterval 最小业务值为 1，score 必须是 1/2/3。
// 返回：newMastery 会钳制在 0~100，newInterval 至少为 1。
// 你以后可改：掌握度增减幅度、间隔增长倍率、连续答对奖励。
// 不建议随手改：score 的 1/2/3 语义；review.cpp、测试脚本和 ReviewLog 都依赖它。
ReviewResult calculateNextReview(int oldMastery, int oldInterval, int oldStreak, int score);

#endif
